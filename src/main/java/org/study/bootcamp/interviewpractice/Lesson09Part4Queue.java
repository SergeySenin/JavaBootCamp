package org.study.bootcamp.interviewpractice;

/**
 * КЛАСС ДЛЯ ДЕМОНСТРАЦИИ КОЛЛЕКЦИИ Queue ИЗ JAVA И ЕЁ ОСОБЕННОСТЕЙ
 *
 * Queue — это «очередь»: обычно FIFO (first in — first out), то есть:
 * 1) добавляем элементы “в хвост”; 2) Забираем элементы “из головы”.
 *
 * Примеры из “соцсети / банк”:
 * - ArrayDeque (двусторонняя очередь на массиве):
 *   - задача:   быстрая очередь задач в одном потоке (обработка событий/сообщений по порядку поступления);
 *   - пример (соцсеть): очередь фоновых задач “обновить ленту / пересчитать рекомендации / отправить уведомления”;
 *   - пример (банк):    очередь операций на обработку (валидация → проведение → запись в журнал).
 * - LinkedList (двусвязный список, также реализует Deque):
 *   - задача: иногда используют как очередь, но чаще заменяют на ArrayDeque (меньше накладных расходов);
 *   - пример  (соцсеть/банк): исторически встречается в старом коде, где важна работа “на концах”.
 * - PriorityQueue (приоритетная очередь):
 *   - задача: обрабатывать “сначала важное”, а не “сначала пришедшее”;
 *   - пример (соцсеть): модерационные события (CRITICAL → HIGH → NORMAL);
 *   - пример (банк):    заявки/проверки с разным приоритетом (fraud-проверка выше обычной).
 *
 * null в Queue:
 * - Во многих реализациях null запрещён (например, ArrayDeque и PriorityQueue),
 *   потому что null используется как сигнал “очередь пуста” для poll()/peek().
 *
 * Особенности API Queue:
 * - offer / poll / peek    — “мягкие” методы:   на пустой очереди poll/peek вернут null (без исключений).
 * - add / remove / element — “строгие” аналоги: на пустой очереди remove/element выбросят NoSuchElementException.
 *
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Критерий                   | ArrayDeque (Deque/Queue на массиве)
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Порядок элементов          | FIFO для методов Queue; дополнительно есть операции с головой/хвостом как у Deque
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Дубликаты                  | Разрешены
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Допустимость null          | Обычно запрещён (NPE при offer/add)
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Потокобезопасность         | Нет
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Внутренняя структура       | Циклический буфер (массив) с быстрыми операциями на концах
 * | -------------------------- | --------------------------------------------------------------------------------------
 *
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Критерий                   | LinkedList (двусвязный список; также реализует Deque)
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Порядок элементов          | FIFO для методов Queue; дополнительно есть операции с головой/хвостом как у Deque
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Дубликаты                  | Разрешены
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Допустимость null          | Технически допускается, но для Queue лучше избегать
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Потокобезопасность         | Нет
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Внутренняя структура       | Узлы с ссылками prev/next; больше накладных расходов по памяти
 * | -------------------------- | --------------------------------------------------------------------------------------
 *
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Критерий                   | PriorityQueue (приоритетная очередь)
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Порядок элементов          | По приоритету (natural order / Comparator); НЕ FIFO
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Дубликаты                  | Разрешены
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Допустимость null          | Запрещён (NPE)
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Потокобезопасность         | Нет
 * | -------------------------- | --------------------------------------------------------------------------------------
 * | Внутренняя структура       | Бинарная куча (heap) в массиве; peek/poll работают по “верхушке” кучи
 * | -------------------------- | --------------------------------------------------------------------------------------
 *
 * @author Sergey
 */
public class Lesson09Part4Queue {

// O(1) — константно                    | O(n) — линейно                                  | O(log n) — логарифмически
// ≈ “один шаг”; размер почти не влияет | ≈ “пройтись по всем”; рост прямо пропорционален | ≈ “дерево/куча”; рост м-ный

    /**
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | Скорость основных операций | ArrayDeque (как Queue/Deque)
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | offer / poll / peek        | в среднем O(1) (быстро) — операции на концах (голова/хвост)
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | addFirst / addLast         | в среднем O(1) (быстро) — добавление в голову/хвост
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | removeFirst / removeLast   | в среднем O(1) (быстро) — удаление из головы/хвоста
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | Итерация for-each          | O(n) (быстро) — проход по всем элементам
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | Преимущества               | 1) Обычно лучший выбор “очередь в памяти”: быстро и на голове, и на хвосте.
     *  |                            | 2) Низкие накладные расходы по памяти (нет узлов как у LinkedList).
     *  |                            | 3) Хорошая кэш-локальность (массив).
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | Недостатки                 | 1) Нет эффективных операций “в середину”: поиск/удаление произвольного элемента.
     *  |                            | 2) При росте возможны “скачки” времени из-за расширения и копирования массива.
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | Скорость основных операций | LinkedList (как Queue/Deque)
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | offer / poll / peek        | O(1) (быстро) — операции на концах; но больше накладных расходов (узлы/ссылки)
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | addFirst / addLast         | O(1) (быстро) — добавление узла в голову/хвост (перенастройка ссылок).
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | removeFirst / removeLast   | O(1) (быстро) — удаление узла из головы/хвоста (перенастройка ссылок).
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | Итерация for-each          | O(n) (средне) — хуже кэш-локальность, чем у ArrayDeque
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | Преимущества               | 1) Вставка/удаление по известной позиции через итератор (без сдвигов массива).
     *  |                            | 2) Удобен, когда часто “перешивают” последовательность в середине.
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | Недостатки                 | 1) Случайный доступ по индексу и поиск: нужно идти по узлам.
     *  |                            | 2) Низкая кэш-локальность и большой оверхед на узлы (память/GC): часто медленнее.
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | Скорость основных операций | PriorityQueue
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | offer (вставка)            | O(log n) (средне) — поддерживаем кучу (heap)
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | poll  (извлечение)         | O(log n) (средне) — извлекаем верхушку кучи и восстанавливаем структуру
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | peek  (смотреть верх)      | O(1) (быстро) — верхушка кучи
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | remove(value)              | O(n) (медленно) — поиск элемента + перестройка
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | Итерация for-each          | O(n) (средне) — порядок итерации не обязан быть “отсортированным”
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | Преимущества               | 1) Эффективно достаёт “самый приоритетный” элемент (min/max: правило сравнения).
     *  |                            | 2) Подходит для планировщиков, обработки событий по важности, таймеров.
     *  | -------------------------- | ---------------------------------------------------------------------------------
     *  | Недостатки                 | 1) Это не FIFO-очередь: порядок определяется Comparator/natural order.
     *  |                            | 2) null запрещён (NPE).
     *  |                            | 3) Итерация не гарантирует порядок приоритета.
     *  | -------------------------- | ---------------------------------------------------------------------------------
     */

    /*
    Queue — необходимый набор вариантов создания (популярные случаи)

    1) ArrayDeque — базовый выбор “по умолчанию” для очереди в памяти
    java.util.Queue<Тип> имяОчереди = new java.util.ArrayDeque<>();

    Если нужны операции и “с головы”, и “с хвоста” (Deque):
    java.util.Deque<Тип> имяDeque = new java.util.ArrayDeque<>();

    2) LinkedList — тоже Deque/Queue, но обычно уступает ArrayDeque по накладным расходам
    java.util.Queue<Тип> имяОчереди = new java.util.LinkedList<>();
    java.util.Deque<Тип> имяDeque = new java.util.LinkedList<>();

    3) PriorityQueue — когда извлекать нужно “самое важное”, а не “самое раннее”
    java.util.Queue<Тип> имяОчереди = new java.util.PriorityQueue<>();           // natural order
    java.util.Queue<Тип> имяОчереди = new java.util.PriorityQueue<>(comparator); // Comparator

    Важно: у Queue нет стандартных фабрик Queue.of/copyOf/unmodifiableQueue.
    Для “только чтение” обычно используют view как Collection:
    java.util.Collection<Тип> readOnly = java.util.Collections.unmodifiableCollection(mutableQueue);

    LIFO-поведение (как стек) для Deque можно получить view через Collections.asLifoQueue:
    java.util.Queue<Тип> lifoView = java.util.Collections.asLifoQueue(mutableDeque);
     */

    // =================================================================================================================
    // 1) Создание и базовые свойства: size / isEmpty / null-особенности
    // =================================================================================================================
    private static void demonstrateCreationAndBasicProperties() {
        System.out.println("1) Создание Queue и базовые свойства (size / isEmpty / null)");

        java.util.Queue<String> arrayDequeQueue = new java.util.ArrayDeque<>();
        java.util.Queue<String> linkedListQueue = new java.util.LinkedList<>();
        java.util.Queue<String> priorityQueue = new java.util.PriorityQueue<>();

        System.out.println("   Создана очередь на ArrayDeque: " + arrayDequeQueue
                + ", size=" + arrayDequeQueue.size() + ", isEmpty=" + arrayDequeQueue.isEmpty());
        System.out.println("   Создана очередь на LinkedList: " + linkedListQueue
                + ", size=" + linkedListQueue.size() + ", isEmpty=" + linkedListQueue.isEmpty());
        System.out.println("   Создана PriorityQueue:         " + priorityQueue
                + ", size=" + priorityQueue.size()   + ", isEmpty=" + priorityQueue.isEmpty());

        try {
            arrayDequeQueue.offer(null);
            System.out.println("   Неожиданно: ArrayDeque принял null");
        } catch (NullPointerException exception) {
            System.out.println(
                    "   Ожидаемо: NullPointerException для ArrayDeque.offer(null): null запрещён в большинстве очередей"
            );
        }

        linkedListQueue.offer(null);
        System.out.println(
                "   LinkedList.offer(null) выполнен (технически допустимо), но для Queue это плохая практика"
        );

        try {
            priorityQueue.offer(null);
            System.out.println("   Неожиданно: PriorityQueue принял null");
        } catch (NullPointerException exception) {
            System.out.println("   Ожидаемо: NullPointerException для PriorityQueue.offer(null): null запрещён");
        }

        System.out.println();
    }

    // =================================================================================================================
    // 2) offer/poll/peek vs add/remove/element (null vs исключение на пустой очереди)
    // =================================================================================================================
    private static void demonstrateOfferPollPeekVsAddRemoveElement() {
        System.out.println("2) “Мягкие” vs “строгие” методы Queue: offer/poll/peek и add/remove/element");

        java.util.Queue<String> taskQueue = new java.util.ArrayDeque<>();
        System.out.println("   Исходная очередь задач: " + taskQueue);

        System.out.println("   peek() -> " + taskQueue.peek() + " (null означает: очередь пуста)");
        System.out.println("   poll() -> " + taskQueue.poll() + " (null означает: очередь пуста)");

        try {
            taskQueue.element();
            System.out.println("   Неожиданно: element() на пустой очереди вернул значение");
        } catch (java.util.NoSuchElementException exception) {
            System.out.println("   Ожидаемо: NoSuchElementException для element() на пустой очереди");
        }

        try {
            taskQueue.remove();
            System.out.println("   Неожиданно: remove() на пустой очереди вернул значение");
        } catch (java.util.NoSuchElementException exception) {
            System.out.println("   Ожидаемо: NoSuchElementException для remove() на пустой очереди");
        }

        taskQueue.offer("задача: разобрать входящее событие");
        taskQueue.offer("задача: провалидировать данные");
        taskQueue.offer("задача: сохранить в базу данных");
        System.out.println("   После offer(...) x3 -> " + taskQueue);

        System.out.println("   peek()              -> " + taskQueue.peek() + " (первый элемент, без удаления)");
        System.out.println("   poll()              -> " + taskQueue.poll() + " (забрали первый и удалили)");
        System.out.println("   После poll()        -> " + taskQueue);

        taskQueue.add("задача: отправить уведомление");
        System.out.println("   add(\"задача: отправить уведомление\") -> " + taskQueue);

        System.out.println("   element()           -> " + taskQueue.element() + " (первый элемент, без удаления)");
        System.out.println("   remove()            -> " + taskQueue.remove()  + " (забрали первый и удалили)");
        System.out.println("   После remove()      -> " + taskQueue);

        System.out.println();
    }

    // =================================================================================================================
    // 3) ArrayDeque как Deque: голова/хвост; стек через push/pop; view как LIFO-очередь
    // =================================================================================================================
    private static void demonstrateArrayDequeAsDequeAndStack() {
        System.out.println("3) ArrayDeque как Deque: голова/хвост + стек через push/pop");

        java.util.Deque<String> eventDeque = new java.util.ArrayDeque<>();
        eventDeque.addLast("событие: зарегистрирован пользователь");
        eventDeque.addLast("событие: подтверждён email");
        eventDeque.addFirst("событие: получен HTTP-запрос");
        System.out.println("   addFirst/addLast              -> " + eventDeque + " (голова слева)");

        System.out.println("   removeFirst()                 -> " + eventDeque.removeFirst() + " (сняли с головы)");
        System.out.println("   removeLast()                  -> " + eventDeque.removeLast()  + " (сняли с хвоста)");
        System.out.println("   После removeFirst/removeLast  -> " + eventDeque);

        java.util.Deque<String> undoStack = new java.util.ArrayDeque<>();
        undoStack.push("команда: обновить профиль");
        undoStack.push("команда: сменить пароль");
        undoStack.push("команда: включить 2FA");
        System.out.println("   push(...) x3                  -> " + undoStack       + " (верх стека слева)");

        System.out.println("   pop()                         -> " + undoStack.pop() + " (сняли последнюю команду)");
        System.out.println("   После pop()                   -> " + undoStack);

        java.util.Queue<String> lifoQueueView = java.util.Collections.asLifoQueue(undoStack);
        System.out.println("   asLifoQueue(view): poll() ведёт себя как pop()");

        System.out.println("   lifoQueueView.poll() -> " + lifoQueueView.poll());
        System.out.println("   После poll(): stack=" + undoStack + ", view=" + lifoQueueView);

        System.out.println();
    }

    // =================================================================================================================
    // 4) PriorityQueue: порядок по приоритету (не FIFO) и особенности итерации
    // =================================================================================================================
    private static void demonstratePriorityQueueOrdering() {
        System.out.println("4) PriorityQueue: извлечение по приоритету (не FIFO)");

        java.util.Queue<Integer> priorityNumbers = new java.util.PriorityQueue<>();
        priorityNumbers.offer(50);
        priorityNumbers.offer(10);
        priorityNumbers.offer(30);
        priorityNumbers.offer(20);

        System.out.println("   Добавили числа: " + priorityNumbers);
        System.out.println(
                "   Примечание: итерация PriorityQueue не обязана показывать элементы в отсортированном виде"
        );

        System.out.println("   peek()       -> " + priorityNumbers.peek() + " (минимальный элемент по natural order)");
        System.out.println("   poll()       -> " + priorityNumbers.poll() + " (забрали минимальный)");
        System.out.println("   После poll() -> " + priorityNumbers);

        java.util.Comparator<SupportTicket> byPriorityThenId = java.util.Comparator
                .comparingInt(SupportTicket::getPriorityScore)
                .reversed()
                .thenComparing(SupportTicket::getTicketId);

        java.util.Queue<SupportTicket> ticketQueue = new java.util.PriorityQueue<>(byPriorityThenId);
        ticketQueue.offer(new SupportTicket("TCK-1003", 10, "Критично: обнаружен подозрительный перевод"));
        ticketQueue.offer(new SupportTicket("TCK-1002", 7, "Высокий приоритет: отклонён платёж по карте"));
        ticketQueue.offer(new SupportTicket("TCK-1001", 3, "Низкий приоритет: проблема с обновлением фото профиля"));

        System.out.println("   Добавили тикеты (priorityScore: чем больше, тем выше приоритет): " + ticketQueue);
        System.out.println("   peek() -> " + ticketQueue.peek() + " (тикет с максимальным приоритетом)");

        System.out.println("   poll() -> " + ticketQueue.poll());
        System.out.println("   poll() -> " + ticketQueue.poll());
        System.out.println("   poll() -> " + ticketQueue.poll());

        System.out.println("   После poll() x3 -> " + ticketQueue + " (очередь пуста)");

        System.out.println();
    }

    private static final class SupportTicket {
        private final String ticketId;
        private final int priorityScore;
        private final String summary;

        private SupportTicket(String ticketId, int priorityScore, String summary) {
            this.ticketId = ticketId;
            this.priorityScore = priorityScore;
            this.summary = summary;
        }

        public String getTicketId() {
            return ticketId;
        }

        public int getPriorityScore() {
            return priorityScore;
        }

        @Override
        public String toString() {
            return "\nSupportTicket{ticketId=\"" + ticketId
                    + "\", priorityScore=" + priorityScore
                    + ", summary=\"" + summary + "\"}";
        }
    }

    public static void main(String[] args) {
        demonstrateCreationAndBasicProperties();
        demonstrateOfferPollPeekVsAddRemoveElement();
        demonstrateArrayDequeAsDequeAndStack();
        demonstratePriorityQueueOrdering();
    }
}
