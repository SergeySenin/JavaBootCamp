/*
Поле — это переменная, хранящая состояние объекта

    Статическое поле (подробнее в _06)               Статическое поле и константа
    Константное поле                                 совместно объявляются в начале
                                                     для хранения общего состояния класса

    модификаторДоступа тип имяПоля;                  Объявление поля внутри класса
                                                     для хранения данных объекта

    модификаторДоступа тип имяПоля = значение;       Объявление поля с инициализацией
                                                     для задания начального состояния
 */

    private static class Person {
        private String name;
        private int age;

        public Person() {
            this("Без имени", 0);
        }

        public Person(String name, int age) {
            setName(name);
            setAge(age);
        }

        public String getName() {
            return name;
        }

        public void setName(String name) {
            if (name == null || name.isBlank()) {
                this.name = "Без имени";
                return;
            }
            this.name = name.trim();
        }

        public int getAge() {
            return age;
        }

        public void setAge(int age) {
            if (age < 0) {
                this.age = 0;
                return;
            }
            this.age = age;
        }

        public void introduce() {
            System.out.println("Я " + name + ", мне " + age + " лет");
        }

        public int calculateBirthYear(int currentYear) {
            return currentYear - age;
        }
    }

    private static class GreetingService {
        public void printGreeting(String name) {
            System.out.println(buildGreetingMessage(name));
        }

        public String buildGreetingMessage(String name) {
            if (name == null || name.isBlank()) {
                return "Здравствуйте!";
            }
            return "Здравствуйте, " + name.trim() + "!";
        }
    }

/*
Конструктор — это специальный метод, вызываемый при создании объекта (new ИмяКласса(...))
this — ссылка на текущий объект, используется для:
- обращения к полям/методам текущего объекта (this.поле)
- вызова другого конструктора этого же класса (this(...))

    модификаторДоступа ИмяКласса() {                     Конструктор по умолчанию (без параметров)
        this(значение1, значение2);                      используется для задания дефолтного состояния
    }
                                            особенность: если есть this(...), он должен быть первой строкой
                                            ситуации:
                                            - Нужны безопасные дефолты: new Person() -> "Без имени", 0
                                            - Фреймворк/библиотека требует no-args (например, при рефлексии)


    модификаторДоступа ИмяКласса(тип параметр) {         Конструктор с параметром (или параметрами)
        this.поле = параметр;                            используется для явной инициализации состояния объекта
    }
                                            особенность: имя = имя класса; нет return-типа (даже void)
                                            ситуации:
                                            - Объект нельзя создавать «пустым»: new User(username, age)
                                            - Надо сразу установить обязательные поля и валидировать вход


    модификаторДоступа ИмяКласса(тип п1, тип п2) {       Перегруженный конструктор (overloading)
        this.поле1 = п1;                                 используется для разных способов создания объекта
        this.поле2 = п2;
    }
                                            особенность: отличается только списком параметров
                                            ситуации:
                                            - Разные сценарии создания:
                                            new Person(name) -> возраст дефолтный | new Person(name, age) -> весь набор
                                            - Упрощение вызова: один конструктор делегирует в другой через this(...)


    модификаторДоступа ИмяКласса(ИмяКласса другое) {     Конструктор копирования (copy constructor)
        this.поле1 = другое.поле1;                       используется в создании нового объекта на основе существующего
        this.поле2 = другое.поле2;
    }
                                            особенность: обычно копирует значения полей (shallow copy)
                                            ситуации:
                                            - Нужна независимая копия объекта:
                                            копия DTO перед модификацией | snapshot состояния перед изменениями
                                            - Важно: для ссылочных полей часто требуется «глубокое» копирование вручную


    private ИмяКласса() {                                Приватный конструктор
    }                                                    используется для запрета создания объектов извне
                                            особенность: нельзя вызвать new ИмяКласса() снаружи класса
                                            ситуации:
                                            - Утилитарный класс только со static методами/константами (MathUtils)
                                            - Ограничение создания через фабрику: of()/from()/valueOf()
                                            - Singleton (создание одного экземпляра внутри класса)


    static ИмяКласса of/from/valueOf(тип п1, тип п2) {   Статический фабричный метод (альтернатива конструкторам)
        return new ИмяКласса(п1, п2);                    используется для понятных имён создания и доп. логики/валидации
    }
                                            особенность: может возвращать кешированный объект, не обязан создавать новый
                                            ситуации:
                                            - Нужны говорящие имена: Money.ofRubles(100), UserId.from(uuid)
                                            - Нужен кэш/пул: Boolean.valueOf(...), Integer.valueOf(...)
                                            - Нужна предобработка/нормализация до создания объекта
 */

    private static void demonstrateConstructorsAndThis() {
        System.out.println("2) Конструкторы и this");

        System.out.println("Конструктор задаёт начальное состояние объекта при new");
        System.out.println(
                "Person(\"Анна\", 25) → выбран конструктор с параметрами;" +
                " внутри используется this для обращения к полям/методам"
        );
        Person anna = new Person("Анна", 25);
        anna.introduce();
        System.out.println("calculateBirthYear(2025) возвращает int, поэтому результат можно вывести/сохранить");
        System.out.println("Год рождения Анны: " + anna.calculateBirthYear(2025));

        System.out.println(
                "Person() → выбран конструктор без параметров;" +
                        " он делегирует инициализацию в Person(String name, int age) через this(\"Без имени\", 0)"
        );
        Person unknown = new Person();
        unknown.introduce();

        System.out.println();
    }

/*
Метод — это именованный блок кода, выполняющий действие или вычисление
Параметры — переменные в объявлении метода
Аргументы — значения, передаваемые при вызове метода

    Метод без параметра и возврата — для выполнения действия, которое не требует входных данных и результата
    модификаторДоступа void имяМетода() {                             Отсутствие параметра
                                     ;                                Действие
                       ;                                              void - метод не возвращает значение
    }

    Метод с параметром — для выполнения действия с входным значением
    модификаторДоступа void имяМетода(тип параметр) {                 Использование параметра
                                     ;                                Действие с параметром
    }                  ;                                              void - метод не возвращает значение

    Метод с возвратом — для получения значения (расчёт/чтение состояния)
    модификаторДоступа тип имяМетода() {                              Отсутствие параметров
                                     ;                                Действия
        return значение;                                              return - метод возвращает значение типа "тип"
    }

    Метод с параметрами и возвратом — для вычислений по входным данным
    модификаторДоступа тип имяМетода(тип параметр1, тип параметр2) {  Использование параметров
                                    ;                                 Действия с параметрами
        return значение;                                              return - метод возвращает значение типа "тип"
    }

    Перегруженные методы (overloading) — для одной операции с разными вариантами входных данных
    модификаторДоступа тип имяМетода(тип параметр) {                  Версия с одним параметром
        return значение;                                              Одна сигнатура
    }

    модификаторДоступа тип имяМетода(тип п1, тип п2) {                Версия с двумя параметрами
        return другоеЗначение;                                        Другая сигнатура (то же имя)
    }

    Статический метод — для логики, не зависящей от состояния объекта (подробнее в _06)

    Метод с varargs — для переменного числа аргументов одного типа
    модификаторДоступа тип имяМетода(тип... параметры) {              Параметры принимаются как массив
        return значение;
    }

    Рекурсивный метод — для решения задачи через вызов самого себя
    модификаторДоступа тип имяМетода(параметр) {
        if (условиеЗавершения) {                                      Базовый случай
            return конечноеЗначение;
        }
        return имяМетода(изменённыйПараметр);                         Рекурсивный вызов
    }
 */

    private static void demonstrateMethodsParametersArguments() {
        System.out.println("3) Методы, параметры и аргументы");

        GreetingService greeter = new GreetingService();

        System.out.println("Параметры задаются в объявлении метода, аргументы передаются при вызове");
        System.out.println("Вызов void-метода: printGreeting(\"Джульетта\") → печатает сразу:");
        greeter.printGreeting("Джульетта");

        System.out.println("Вызов возвращаемого метода: buildGreetingMessage(\"Ромео\") → возвращает строку:");
        String message = greeter.buildGreetingMessage("Ромео");
        System.out.println(message + " (строка получена как результат метода)");

        System.out.println();
    }

    private static void demonstrateGettersSetters() {
        System.out.println("4) Геттеры и сеттеры");

        System.out.println("Поля private: прямого доступа нет, состояние меняется через методы");
        System.out.println(
                "Сеттеры выполняют простую валидацию/нормализацию," +
                " чтобы объект оставался в корректном состоянии"
        );
        System.out.println("Геттеры возвращают текущее значение поля");

        Person person = new Person("  ", -5);
        System.out.println("После конструктора с некорректными значениями (\"  \", -5) сработали дефолты:");
        person.introduce();

        person.setName("Виктор");
        person.setAge(27);
        System.out.println("После setName/setAge:");
        System.out.println(person.getName() + ", " + person.getAge() + " лет" + " (после обновления)");

        System.out.println();
    }

    public static void main(String[] args) {
        demonstrateClassAndObject();
        demonstrateConstructorsAndThis();
        demonstrateMethodsParametersArguments();
        demonstrateGettersSetters();
    }
